#!/usr/bin/env python3
"""Build a relocatable plugin or install a skill into an explicitly chosen config."""
import argparse
try:
    import fcntl
except ImportError:
    fcntl = None
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ROLES = ('goal-worker', 'goal-mech-worker', 'goal-critic', 'goal-checker-req', 'goal-adjudicator')


def require(ok, message):
    if not ok:
        raise ValueError(message)


def plugin_entry(root=ROOT):
    text = (root/'SKILL.md').read_text()
    end = text.index('\n---', 4)+4
    binding = ('\n\n<!-- Generated by scripts/goal_install.py; edit the root SKILL.md. -->\n'
               '本插件的实施目录是 `${CLAUDE_PLUGIN_ROOT}`。下文 `<skill>`、`${GOAL_SKILL}` '
               '和所有相对资源路径都以此目录为准，宿主显示的 Base directory 仅是发现入口。'
               '给 worker/checker 的资源路径须从实施目录构造为绝对路径。'
               '调用本插件的角色时使用 `goal-loop-host:goal-worker`、'
               '`goal-loop-host:goal-mech-worker`、`goal-loop-host:goal-critic`、'
               '`goal-loop-host:goal-checker-req`、`goal-loop-host:goal-adjudicator`；'
               '其余契约、预算、权限和终验协议不变。\n')
    return text[:end]+binding+text[end:]


def inventory():
    names = json.loads((ROOT/'assets/install-files.json').read_text())
    require(isinstance(names, list) and names and all(isinstance(name, str) and name for name in names),
            'invalid install inventory: expected nonempty file paths')
    require(len(names) == len(set(names)), 'invalid install inventory: duplicate file paths')
    for name in names:
        path = Path(name)
        require(not path.is_absolute() and '..' not in path.parts, 'unsafe install path')
        source = ROOT/path
        require(source.is_file() and source.resolve().is_relative_to(ROOT), 'missing/escaping payload: '+name)
    require((ROOT/'skills/goal-loop/SKILL.md').read_text() == plugin_entry(),
            'plugin entry is stale; run goal_install.py sync-entry after changing SKILL.md')
    return names


def doctor():
    require(sys.version_info >= (3, 10) and os.name == 'posix', 'POSIX Python 3.10+ required (tested: 3.12/3.14)')
    require(fcntl is not None and hasattr(fcntl, 'flock') and hasattr(os, 'killpg'), 'directory locks and process groups required')
    for name in ('bash', 'grep', 'sed', 'tr', 'sort', 'find', 'cksum'):
        require(shutil.which(name), 'missing dependency: '+name)
    require(any(shutil.which(name) for name in ('sha256sum', 'shasum', 'openssl')),
            'missing SHA-256 tool: install sha256sum, shasum or openssl')
    result = subprocess.run(['bash', '-c', '. "$1"; gawk \'BEGIN {if (match("ok", /(ok)/, a)) print a[1]}\'',
                             'goal-install', str(ROOT/'scripts/goal_parse.sh')],
                            text=True, capture_output=True, timeout=10)
    require(result.returncode == 0 and result.stdout.strip() == 'ok', 'GNU awk unavailable: install gawk; '+result.stderr.strip())
    return dict(python=sys.version.split()[0], posix=True, gawk=True)


def copy_payload(destination, names):
    for name in names:
        target = destination/name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT/name, target)


def config_parents(destination):
    for name in ('skills', 'agents'):
        path = destination/name
        require(not path.is_symlink() and (not path.exists() or path.is_dir()),
                'installation parent must be a real directory: '+str(path))


def install(kind, destination, companion=False):
    names = inventory()
    dependencies = doctor()
    destination = Path(destination).absolute()
    require(not destination.is_symlink(), 'destination cannot be a symlink')
    if kind == 'plugin':
        require(not destination.exists(), 'plugin destination already exists; choose a fresh directory')
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='.goal-plugin-', dir=destination.parent) as temporary:
            stage = Path(temporary)/'payload';stage.mkdir()
            copy_payload(stage, names)
            require(not destination.exists(), 'plugin destination appeared during build')
            stage.rename(destination)
        return dict(kind=kind, path=str(destination), files=len(names), dependencies=dependencies,
                    invoke='/goal-loop-host:goal-loop', hooks='bundled; activated by the host plugin loader')
    config_parents(destination)
    targets = [destination/'skills/goal-loop', *[destination/'agents'/(name+'.md') for name in ROLES]]
    if companion:
        targets.append(destination/'skills/contract-forge')
    require(not any(p.exists() or p.is_symlink() for p in targets),
            'installation would overwrite an existing skill/agent; choose a clean config directory')
    destination.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(destination/'.goal-loop-install.lock', os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, 'a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        config_parents(destination)
        installed = []
        with tempfile.TemporaryDirectory(prefix='.goal-install-', dir=destination) as temporary:
            stage = Path(temporary);payload=stage/'payload';payload.mkdir()
            copy_payload(payload, names)
            # Claude discovers the root SKILL.md here. Bundled plugin files
            # remain inert unless explicitly loaded as a plugin.
            prepared = [(payload, targets[0])]
            for name in ROLES:
                card = stage/(name+'.md');text=(ROOT/'agents'/(name+'.md')).read_text()
                end=text.index('\n---',4)+4
                card.write_text(text[:end]+'\n\nSkill resources: '+str(targets[0])+' (use absolute paths from this root).\n'+text[end:])
                prepared.append((card,destination/'agents'/(name+'.md')))
            if companion:
                card=stage/'contract-forge';shutil.copytree(ROOT/'companions/contract-forge',card)
                prepared.append((card,targets[-1]))
            try:
                for source,target in prepared:
                    config_parents(destination)
                    target.parent.mkdir(parents=True,exist_ok=True)
                    require(not target.exists() and not target.is_symlink(), 'target appeared during install: '+str(target))
                    source.rename(target);installed.append(target)
            except BaseException:
                for target in reversed(installed):
                    shutil.rmtree(target) if target.is_dir() else target.unlink()
                raise
    return dict(kind=kind,path=str(targets[0]),agents=list(ROLES),companion=companion,
                dependencies=dependencies,hooks='not installed; use the explicit host bridge or the full plugin')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    commands=parser.add_subparsers(dest='command',required=True)
    commands.add_parser('doctor');commands.add_parser('sync-entry')
    build=commands.add_parser('plugin');build.add_argument('--output',required=True)
    skill=commands.add_parser('skill');skill.add_argument('--config-dir',required=True);skill.add_argument('--with-companion',action='store_true')
    args=parser.parse_args()
    if args.command=='sync-entry':
        target=ROOT/'skills/goal-loop/SKILL.md';target.parent.mkdir(parents=True,exist_ok=True);target.write_text(plugin_entry());return
    result=doctor() if args.command=='doctor' else install(args.command,
        args.output if args.command=='plugin' else args.config_dir,getattr(args,'with_companion',False))
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__':
    try:
        main()
    except (ValueError,OSError,subprocess.SubprocessError) as exc:
        print('INSTALL: ERROR '+str(exc),file=sys.stderr);sys.exit(2)
